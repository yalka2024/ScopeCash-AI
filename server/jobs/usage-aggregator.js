/**
 * Usage aggregator + lifecycle sweep — runs every hour. Four jobs:
 *
 *   1. Reconcile UsageCounter rows against the raw UsageEvent log for the
 *      current period. Catches drift if a counter upsert ever fails.
 *   2. Push metered usage to Stripe (best-effort) for tiers configured
 *      with subscription-item ids.
 *   3. Run dunning.sweepLifecycles() to escalate past_due → grace → suspend.
 *   4. Check AiSpendEvent vs TenantCostEvent AI-cost reconciliation and log
 *      a warning on drift — detection only, never auto-corrects (unlike #1,
 *      TenantCostEvent is an append-only event log, not a cache/rollup
 *      safe to silently overwrite from another log after the fact).
 *
 * Generated by platform-generator (Tier 10).
 */
const prisma = require('../lib/prisma');
const ent = require('../lib/entitlements');
const dunning = require('../lib/billing/dunning');
const stripe = require('../lib/billing/stripe');
const costAttribution = require('../lib/cost-attribution');
const { runWithSystemAccess } = require('../lib/tenant-context');

async function reconcileCounters() {
  const period = ent.currentPeriodKey();
  const rows = await prisma.$queryRawUnsafe(`
    SELECT orgId, meter, COALESCE(SUM(quantity), 0) AS total
    FROM UsageEvent
    WHERE period = ?
    GROUP BY orgId, meter
  `, period).catch(() => []);

  let fixed = 0;
  for (const r of rows) {
    await prisma.usageCounter.upsert({
      where: { orgId_meter_period: { orgId: r.orgId, meter: r.meter, period } },
      create: { orgId: r.orgId, meter: r.meter, period, value: BigInt(r.total) },
      update: { value: BigInt(r.total) },
    }).catch(() => {});
    fixed++;
  }
  return { period, counters: fixed };
}

/**
 * Detection-only: logs a warning if the current period's AiSpendEvent and
 * TenantCostEvent(ai_tokens) totals have drifted apart for any org. See
 * lib/cost-attribution.js#reconcileAiSpend for what this catches and why
 * it deliberately doesn't self-heal like reconcileCounters() above.
 */
async function checkAiSpendReconciliation() {
  const result = await runWithSystemAccess(() => costAttribution.reconcileAiSpend()).catch(() => null);
  if (result && !result.all_reconciled) {
    const drifted = result.orgs.filter((o) => !o.reconciled);
    console.error(JSON.stringify({
      type: 'ai_spend_reconciliation_drift',
      period: result.period,
      drifted_orgs: drifted.length,
      total_delta_usd: result.total_delta_usd,
    }));
  }
  return result;
}

async function reportMeteredUsageToStripe() {
  if (!stripe.isConfigured()) return { sent: 0, skipped: 'not_configured' };
  // No-op skeleton: a real deployment would map (orgId, meter) → stripe
  // subscription_item id by looking at metadata persisted at checkout time.
  // Left intentionally minimal — overage SKU wiring is per-customer.
  return { sent: 0 };
}

async function runOnce() {
  const out = { startedAt: new Date().toISOString() };
  out.reconcile = await reconcileCounters();
  out.lifecycle = await dunning.sweepLifecycles();
  out.stripeUsage = await reportMeteredUsageToStripe();
  out.aiSpendReconciliation = await checkAiSpendReconciliation();
  out.completedAt = new Date().toISOString();
  console.log(JSON.stringify({ type: 'usage_aggregator_run', ...out }));
  return out;
}

/** Called from worker.js if BullMQ is available; otherwise plain setInterval. */
function startScheduler({ intervalMs = 60 * 60 * 1000 } = {}) {
  if (process.env.BILLING_AGGREGATOR_DISABLED === '1') return null;
  const tick = async () => { try { await runOnce(); } catch (e) { console.error(e); } };
  // First run after 60s so boot isn't blocked.
  const kick = setTimeout(tick, 60_000);
  const handle = setInterval(tick, intervalMs);
  return () => { clearTimeout(kick); clearInterval(handle); };
}

module.exports = { runOnce, reconcileCounters, reportMeteredUsageToStripe, checkAiSpendReconciliation, startScheduler };

