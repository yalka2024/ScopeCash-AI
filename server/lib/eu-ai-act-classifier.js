// ───────────────────────────────────────────────────────
//  GPAI / Foundation models — Article 53-55
// ───────────────────────────────────────────────────────

function isGPAI(a) {
  const t = a.description.toLowerCase();
  return /\b(foundation.model|general.purpose|gpai|llm|large.language.model|frontier.model)/.test(t);
}

function isSystemicRiskGPAI(a) {
  if (!isGPAI(a)) return false;
  const t = a.description.toLowerCase();
  // Heuristic: explicit mention of training compute >= 10^25 FLOP, or
  // models named in Commission designations (kept user-extensible).
  return /\b(10\^?25|10e25|systemic.risk|frontier|gpt-?[4-9]|claude-?[3-9]|gemini)/.test(t);
}

// ───────────────────────────────────────────────────────
//  Helpers
// ───────────────────────────────────────────────────────

function _scoreFromVerdict(verdict, matchCount) {
  // 0-100 — used for sort & dashboard tiles
  switch (verdict) {
    case 'prohibited':  return 100;
    case 'high':        return Math.min(95, 70 + matchCount * 5);
    case 'limited':     return 30 + matchCount * 5;
    case 'minimal':     return 10;
    default:            return 0;
  }
}

function _normalize(input) {
  return {
    description:    String(input.description || '').slice(0, 5000),
    sector:         input.sector || 'other',
    decisionImpact: input.decisionImpact || 'unclear',
    dataSensitive:  Array.isArray(input.dataSensitive) ? input.dataSensitive : [],
    scope:          input.scope || 'eu_only',
    providerRole:   input.providerRole || 'deployer',
  };
}

function _validate(input) {
  const errors = [];
  if (!input.description || input.description.length < 20) {
    errors.push('description must be at least 20 characters');
  }
  if (!SECTORS.includes(input.sector)) {
    errors.push(`sector must be one of: ${SECTORS.join(', ')}`);
  }
  if (!DECISION_IMPACTS.includes(input.decisionImpact)) {
    errors.push(`decisionImpact must be one of: ${DECISION_IMPACTS.join(', ')}`);
  }
  if (!Array.isArray(input.dataSensitive)
      || input.dataSensitive.some((d) => !DATA_SENSITIVE.includes(d))) {
    errors.push(`dataSensitive must be an array of: ${DATA_SENSITIVE.join(', ')}`);
  }
  if (!DEPLOYMENT_SCOPES.includes(input.scope)) {
    errors.push(`scope must be one of: ${DEPLOYMENT_SCOPES.join(', ')}`);
  }
  if (!PROVIDER_ROLES.includes(input.providerRole)) {
    errors.push(`providerRole must be one of: ${PROVIDER_ROLES.join(', ')}`);
  }
  return errors;
}

// ───────────────────────────────────────────────────────
//  Public API: classify(input) → Verdict
// ───────────────────────────────────────────────────────

const HIGH_RISK_OBLIGATIONS = [
  { article: '9',  title: 'Risk-management system' },
  { article: '10', title: 'Data governance & quality' },
  { article: '11', title: 'Technical documentation (Annex IV)' },
  { article: '12', title: 'Logging & traceability' },
  { article: '13', title: 'Transparency & information to deployers' },
  { article: '14', title: 'Human oversight' },
  { article: '15', title: 'Accuracy, robustness & cybersecurity' },
  { article: '17', title: 'Quality-management system' },
  { article: '43', title: 'Conformity assessment' },
  { article: '49', title: 'EU declaration of conformity & CE marking' },
  { article: '71', title: 'Registration in the EU database' },
  { article: '72', title: 'Post-market monitoring plan' },
];

function classify(rawInput) {
  const input = _normalize(rawInput);
  const validationErrors = _validate(input);
  if (validationErrors.length) {
    const err = new Error('invalid_assessment_input');
    err.code = 'invalid_assessment_input';
    err.details = validationErrors;
    throw err;
  }

  // Scope short-circuit: if no EU deployment, advisory only.
  if (input.scope === 'outside_eu') {
    return {
      verdict:        'minimal',
      severity:       'green',
      title:          'Out of EU AI Act scope',
      reasoning:      ['System reportedly not placed on the EU market or used in the EU.'],
      articles:       [],
      annexPoints:    [],
      transparency:   [],
      deadline:       null,
      obligations:    [],
      estimatedHours: '0-2 hours',
      score:          5,
      isGPAI:         isGPAI(input),
      version:        VERSION,
      assessedAt:     new Date().toISOString(),
    };
  }

  // 1) Prohibited (Article 5)
  const prohibitedMatches = PROHIBITED_RULES.filter((r) => r.matcher(input));
  if (prohibitedMatches.length) {
    return {
      verdict:        'prohibited',
      severity:       'red',
      title:          'Prohibited under Article 5',
      reasoning:      prohibitedMatches.map((r) => `Article ${r.article}: ${r.title}`),
      articles:       prohibitedMatches.map((r) => ({ ref: r.article, title: r.title })),
      annexPoints:    [],
      transparency:   [],
      deadline:       '2 February 2025 (already in force)',
      obligations:    [
        { article: '5', title: 'Cease deployment in the EU' },
        { article: 'N/A', title: 'Consult an EU AI Act specialist lawyer immediately' },
      ],
      estimatedHours: 'Stop-work; legal review required',
      score:          _scoreFromVerdict('prohibited', prohibitedMatches.length),
      isGPAI:         isGPAI(input),
      version:        VERSION,
      assessedAt:     new Date().toISOString(),
    };
  }

  // 2) High-risk (Annex III)
  const annexMatches = ANNEX_III_RULES.filter((r) => r.matcher(input));
  if (annexMatches.length) {
    const transparency = ARTICLE_50_RULES.filter((r) => r.matcher(input))
      .map((r) => ({ ref: r.article, title: r.title, obligation: r.obligation }));
    return {
      verdict:        'high',
      severity:       'orange',
      title:          'High-risk under Annex III',
      reasoning:      annexMatches.map((r) => `Annex III, point ${r.point}: ${r.title}`),
      articles:       [],
      annexPoints:    annexMatches.map((r) => ({ ref: r.point, title: r.title })),
      transparency,
      deadline:       '2 August 2026',
      obligations:    HIGH_RISK_OBLIGATIONS,
      estimatedHours: '200-400 hours over 6-12 months',
      score:          _scoreFromVerdict('high', annexMatches.length),
      isGPAI:         isGPAI(input),
      systemicRisk:   isSystemicRiskGPAI(input),
      version:        VERSION,
      assessedAt:     new Date().toISOString(),
    };
  }

  // 3) Limited risk (Article 50)
  const a50Matches = ARTICLE_50_RULES.filter((r) => r.matcher(input));
  if (a50Matches.length) {
    return {
      verdict:        'limited',
      severity:       'yellow',
      title:          'Limited risk — transparency obligations apply',
      reasoning:      a50Matches.map((r) => `Article ${r.article}: ${r.title}`),
      articles:       a50Matches.map((r) => ({ ref: r.article, title: r.title })),
      annexPoints:    [],
      transparency:   a50Matches.map((r) => ({ ref: r.article, title: r.title, obligation: r.obligation })),
      deadline:       '2 August 2026',
      obligations:    a50Matches.map((r) => ({ article: r.article, title: r.obligation })),
      estimatedHours: '5-20 hours',
      score:          _scoreFromVerdict('limited', a50Matches.length),
      isGPAI:         isGPAI(input),
      version:        VERSION,
      assessedAt:     new Date().toISOString(),
    };
  }

  // 4) Minimal risk
  return {
    verdict:        'minimal',
    severity:       'green',
    title:          'Minimal risk',
    reasoning:      ['No specific obligations under the EU AI Act.'],
    articles:       [],
    annexPoints:    [],
    transparency:   [],
    deadline:       null,
    obligations:    [
      { article: '95', title: 'Voluntary code of conduct (recommended)' },
    ],
    estimatedHours: '0-5 hours',
    score:          _scoreFromVerdict('minimal', 0),
    isGPAI:         isGPAI(input),
    version:        VERSION,
    assessedAt:     new Date().toISOString(),
  };
}

