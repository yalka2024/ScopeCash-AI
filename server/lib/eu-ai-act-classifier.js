/**
 * EU AI Act classifier — pure rules engine.
 *
 * Inputs an AssessmentInput (free-text description + structured answers)
 * and returns a Verdict with:
 *  - risk classification (prohibited|high|limited|minimal)
 *  - matched articles / annex points (with citations)
 *  - reasoning (human-readable)
 *  - obligations (the work the operator must do)
 *  - deadline (legal compliance date)
 *  - estimated effort (hours range)
 *  - score (0-100, used for sorting & dashboards)
 *
 * No AI model required for the verdict itself — these are deterministic
 * rules derived from Regulation (EU) 2024/1689 (AI Act), final OJ text.
 *
 * Source citations point to the AI Act articles & annexes; the file is
 * kept readable so legal teams can audit the rules. Update when the
 * Commission publishes Implementing Acts that change scope.
 *
 * Generated by platform-generator (Tier 20 — Domain Logic).
 */

